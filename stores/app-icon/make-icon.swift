// Renders the OpenBook wordmark icon: "Open" ink + "Book" brick on cream, Playfair Display Bold
// (same font/colours as the web Logo in web/src/components/Header.tsx). Run from repo root:
//   swift stores/app-icon/make-icon.swift
import CoreText; import CoreGraphics; import ImageIO; import Foundation

let dir = "stores/app-icon/"
let cream = "#FBF6EC", ink = "#3B2A1A", brick = "#C2410C"  // web --tone-cream, --tone-ink, --color-brick (ink text was unreadable on cream)

let data = try! Data(contentsOf: URL(fileURLWithPath: dir + "PlayfairDisplay-latin.woff2"))
let desc = (CTFontManagerCreateFontDescriptorsFromData(data as CFData) as! [CTFontDescriptor])[0]
let wght = 0x77676874 // 'wght' axis
let font = CTFontCreateWithFontDescriptor(CTFontDescriptorCreateCopyWithAttributes(desc,
  [kCTFontVariationAttribute: [wght: 700]] as CFDictionary), 100, nil)

// Glyph outlines of "Open" and "Book", laid out as one line with the font's kerning.
let line = CTLineCreateWithAttributedString(NSAttributedString(string: "OpenBook",
  attributes: [NSAttributedString.Key(kCTFontAttributeName as String): font]))
let open = CGMutablePath(), book = CGMutablePath()
for run in CTLineGetGlyphRuns(line) as! [CTRun] {
  let n = CTRunGetGlyphCount(run)
  var gl = [CGGlyph](repeating: 0, count: n), pos = [CGPoint](repeating: .zero, count: n), idx = [CFIndex](repeating: 0, count: n)
  CTRunGetGlyphs(run, CFRange(), &gl); CTRunGetPositions(run, CFRange(), &pos); CTRunGetStringIndices(run, CFRange(), &idx)
  for i in 0..<n {
    guard let p = CTFontCreatePathForGlyph(font, gl[i], nil) else { continue }
    (idx[i] < 4 ? open : book).addPath(p, transform: CGAffineTransform(translationX: pos[i].x, y: pos[i].y))
  }
}
let all = CGMutablePath(); all.addPath(open); all.addPath(book)
let box = all.boundingBoxOfPath

// Map text into a 512 canvas (y down), `width` wide, optically centred.
func place(_ p: CGPath, width: CGFloat) -> CGPath {
  let s = width / box.width
  var t = CGAffineTransform(translationX: 256, y: 256).scaledBy(x: s, y: -s)
    .translatedBy(x: -box.midX, y: -box.midY)
  return p.copy(using: &t)!
}
func svgPath(_ p: CGPath) -> String {
  var out = ""; let f = { (v: CGFloat) in String(format: "%.2f", v) }
  p.applyWithBlock { e in
    let a = e.pointee.points
    switch e.pointee.type {
    case .moveToPoint: out += "M\(f(a[0].x)) \(f(a[0].y))"
    case .addLineToPoint: out += "L\(f(a[0].x)) \(f(a[0].y))"
    case .addQuadCurveToPoint: out += "Q\(f(a[0].x)) \(f(a[0].y)) \(f(a[1].x)) \(f(a[1].y))"
    case .addCurveToPoint: out += "C\(f(a[0].x)) \(f(a[0].y)) \(f(a[1].x)) \(f(a[1].y)) \(f(a[2].x)) \(f(a[2].y))"
    case .closeSubpath: out += "Z"
    @unknown default: break
    }
  }
  return out
}

// 1) Full-bleed icon (iOS, Play): text 80% of the canvas.
let fullW: CGFloat = 410
let svg = """
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 512 512">
  <title>OpenBook icon</title>
  <desc>Wordmark OpenBook: Open in ink, Book in brick, on book-paper cream. Generated by make-icon.swift.</desc>
  <rect width="512" height="512" fill="\(cream)"/>
  <path fill="\(ink)" d="\(svgPath(place(open, width: fullW)))"/>
  <path fill="\(brick)" d="\(svgPath(place(book, width: fullW)))"/>
</svg>
"""
try! svg.write(toFile: dir + "icon.svg", atomically: true, encoding: .utf8)

// 2) Android adaptive foreground: text inside the 66/108 safe circle (≈ 300 of 512 wide).
let fgW: CGFloat = 300
let vector = """
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by stores/app-icon/make-icon.swift — edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="512" android:viewportHeight="512">
    <path android:fillColor="\(ink)" android:pathData="\(svgPath(place(open, width: fgW)))"/>
    <path android:fillColor="\(brick)" android:pathData="\(svgPath(place(book, width: fgW)))"/>
</vector>
"""
try! vector.write(toFile: "android/app/src/main/res/drawable/ic_launcher_foreground.xml", atomically: true, encoding: .utf8)

// 3) PNGs, opaque (App Store and Play reject alpha).
func hex(_ h: String) -> CGColor {
  let v = Int(h.dropFirst(), radix: 16)!
  return CGColor(srgbRed: CGFloat(v >> 16 & 255) / 255, green: CGFloat(v >> 8 & 255) / 255, blue: CGFloat(v & 255) / 255, alpha: 1)
}
func png(_ size: Int, _ path: String) {
  let c = CGContext(data: nil, width: size, height: size, bitsPerComponent: 8, bytesPerRow: 0,
    space: CGColorSpace(name: CGColorSpace.sRGB)!, bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue)!
  let k = CGFloat(size) / 512
  c.setFillColor(hex(cream)); c.fill(CGRect(x: 0, y: 0, width: size, height: size))
  c.translateBy(x: 0, y: CGFloat(size)); c.scaleBy(x: k, y: -k)  // to the SVG's y-down space
  for (p, col) in [(open, ink), (book, brick)] { c.addPath(place(p, width: fullW)); c.setFillColor(hex(col)); c.fillPath() }
  let d = CGImageDestinationCreateWithURL(URL(fileURLWithPath: path) as CFURL, "public.png" as CFString, 1, nil)!
  CGImageDestinationAddImage(d, c.makeImage()!, nil); CGImageDestinationFinalize(d)
}
